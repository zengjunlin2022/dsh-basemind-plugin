import test from 'node:test';
import assert from 'node:assert/strict';

import { parseChecksums, digestFor } from '../lib/binary/checksums.js';
import { assetFor } from '../lib/upstream.js';

const DIGEST = 'ab'.repeat(32);
const OTHER = 'cd'.repeat(32);

test('parses the sha256sum text-mode format (two spaces and a bare name)', () => {
  const digests = parseChecksums(DIGEST + '  basemind-x86_64-unknown-linux-gnu.tar.gz\n');
  assert.equal(digests.size, 1);
  assert.equal(digests.get('basemind-x86_64-unknown-linux-gnu.tar.gz'), DIGEST);
});

test('parses the sha256sum binary-mode format (asterisk before the name)', () => {
  const digests = parseChecksums(DIGEST + ' *basemind-aarch64-apple-darwin.tar.gz\n');
  assert.equal(digests.get('basemind-aarch64-apple-darwin.tar.gz'), DIGEST);
});

test('accepts a single space, tabs, CRLF and upper-case digests', () => {
  const digests = parseChecksums(
    DIGEST.toUpperCase() + ' basemind-x86_64-pc-windows-msvc.zip\r\n' + OTHER.toUpperCase() + '\tbasemind-aarch64-unknown-linux-gnu.tar.gz\r\n',
  );
  assert.equal(digests.get('basemind-x86_64-pc-windows-msvc.zip'), DIGEST);
  assert.equal(digests.get('basemind-aarch64-unknown-linux-gnu.tar.gz'), OTHER);
  for (const value of digests.values()) assert.equal(value, value.toLowerCase());
});

test('ignores comments, blank lines, short digests and unrelated text', () => {
  const digests = parseChecksums(
    [
      '# generated by the release workflow',
      '',
      '   ',
      'not a checksum line at all',
      DIGEST.slice(0, 63) + '  truncated-digest.tar.gz',
      'zz'.repeat(32) + '  non-hex.tar.gz',
      DIGEST + '  good.tar.gz',
      DIGEST,
    ].join('\n'),
  );

  assert.deepEqual([...digests.keys()], ['good.tar.gz']);
});

test('a later line for the same asset wins without duplicating the key', () => {
  const digests = parseChecksums(DIGEST + '  same.zip\n' + OTHER + '  same.zip\n');
  assert.equal(digests.size, 1);
  assert.equal(digests.get('same.zip'), OTHER);
});

test('names may contain spaces and are not trimmed away', () => {
  const digests = parseChecksums(DIGEST + '  my asset name.zip\n');
  assert.equal(digests.get('my asset name.zip'), DIGEST);
});

test('missing asset line resolves to undefined instead of a wrong digest', () => {
  const digests = parseChecksums(DIGEST + '  basemind-x86_64-pc-windows-msvc.zip\n');
  const asset = assetFor('windows-x64');
  assert.equal(digestFor(digests, asset.name), DIGEST);
  assert.equal(digestFor(digests, 'basemind-aarch64-apple-darwin.tar.gz'), undefined);
  assert.equal(digestFor(digests, ''), undefined);
  assert.equal(digestFor(digests, asset.name + ' '), undefined);
});

test('non-string input yields an empty map, not a throw', () => {
  assert.equal(parseChecksums(undefined).size, 0);
  assert.equal(parseChecksums(null).size, 0);
  const digests = parseChecksums(DIGEST + '  x.zip\n');
  assert.equal(digestFor(null, 'x.zip'), undefined);
  assert.equal(digestFor([], 'x.zip'), undefined);
});
